import {
  Activity,
  Brain,
  CalendarClock,
  CreditCard,
  GitFork,
  Globe,
  History,
  Inbox,
  LayoutDashboard,
  LifeBuoy,
  MessageCircle,
  MessageSquare,
  Moon,
  OctagonPause,
  Phone,
  Play,
  Plus,
  Radar,
  RadioTower,
  Receipt,
  RotateCw,
  ScrollText,
  Send,
  Settings2,
  ShieldCheck,
  Sparkles,
  SquareTerminal,
  Sun,
  Users,
  Workflow,
  type LucideIcon,
} from "lucide-react";

const ICONS: Record<string, LucideIcon> = {
  activity: Activity,
  brain: Brain,
  "calendar-clock": CalendarClock,
  "credit-card": CreditCard,
  "git-fork": GitFork,
  globe: Globe,
  history: History,
  inbox: Inbox,
  "layout-dashboard": LayoutDashboard,
  "life-buoy": LifeBuoy,
  "message-circle": MessageCircle,
  "message-square": MessageSquare,
  moon: Moon,
  "octagon-pause": OctagonPause,
  phone: Phone,
  play: Play,
  plus: Plus,
  radar: Radar,
  "radio-tower": RadioTower,
  receipt: Receipt,
  "rotate-cw": RotateCw,
  "scroll-text": ScrollText,
  send: Send,
  "settings-2": Settings2,
  "shield-check": ShieldCheck,
  sparkles: Sparkles,
  "square-terminal": SquareTerminal,
  sun: Sun,
  users: Users,
  workflow: Workflow,
};

export function Icon({ name, size = 16, color, className }: { name: string; size?: number; color?: string; className?: string }) {
  const C = ICONS[name] ?? Sparkles;
  return <C size={size} color={color} className={className} aria-hidden="true" style={{ flex: "none" }} />;
}
